import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'

/*
 * Writes resources/lang/{locale}/locale.php — the ECharts locale object
 * (month and day names, toolbox, legend and aria strings) — for every
 * Filament locale that ECharts ships a translation for.
 *
 *   npm run locales
 *
 * The other Filament locales have no ECharts translation; their locale.php
 * files are maintained by hand and are not touched here.
 */
const require = createRequire(import.meta.url)

// Filament locale => ECharts i18n file (echarts/i18n/lang{NAME}-obj.js).
const locales = {
    ar: 'AR',
    cs: 'CS',
    de: 'DE',
    el: 'EL',
    en: 'EN',
    es: 'ES',
    fa: 'FA',
    fi: 'FI',
    fr: 'FR',
    hu: 'HU',
    it: 'IT',
    ja: 'JA',
    ko: 'KO',
    lv: 'LV',
    nb: 'nb-NO',
    nl: 'NL',
    pl: 'PL',
    pt_BR: 'PT-br',
    ro: 'RO',
    ru: 'RU',
    sl: 'SI',
    sv: 'SV',
    th: 'TH',
    tr: 'TR',
    uk: 'UK',
    vi: 'VI',
    zh_CN: 'ZH',
}

// Mistakes in the upstream files, corrected here until ECharts fixes them.
const fixes = {
    // langSV names the series with {name}, which this sentence never fills in,
    // and drops the {seriesType} every other locale reads out.
    sv: (object) => {
        object.aria.series.single.withName =
            ' med typ {seriesType} som heter {seriesName}.'
    },
}

function php(value, depth) {
    const pad = '    '.repeat(depth + 1)
    const end = '    '.repeat(depth)

    if (Array.isArray(value)) {
        return `[\n${value.map((item) => `${pad}${php(item, depth + 1)},\n`).join('')}${end}]`
    }

    if (value !== null && typeof value === 'object') {
        const entries = Object.entries(value).map(
            ([key, item]) => `${pad}'${key}' => ${php(item, depth + 1)},\n`,
        )

        return `[\n${entries.join('')}${end}]`
    }

    return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

for (const [locale, name] of Object.entries(locales)) {
    const object = structuredClone(require(`echarts/i18n/lang${name}-obj.js`))
    fixes[locale]?.(object)
    const dir = `resources/lang/${locale}`

    mkdirSync(dir, { recursive: true })
    writeFileSync(
        `${dir}/locale.php`,
        `<?php\n\n// Generated by \`npm run locales\` from echarts/i18n/lang${name}-obj.js.\n\nreturn ${php(object, 0)};\n`,
    )
}

console.log(`Wrote ${Object.keys(locales).length} locales.`)
